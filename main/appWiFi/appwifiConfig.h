#ifndef MICROPLASTIC_APPWIFICONFIG_H
#define MICROPLASTIC_APPWIFICONFIG_H

#include "driver/gpio.h"

/* ------------------------------------------------------------------------
 * Точка доступу (SoftAP), яку піднімає Captive Portal
 * ------------------------------------------------------------------------ */
/* Ім'я мережі: префікс + 4 hex-символи з MAC-адреси, напр. "Microplastic-A1B2" */
#define WIFI_MGR_AP_SSID_PREFIX               "Microplastic-"
/* Початковий канал AP. Після підключення STA до роутера AP автоматично
 * переходить на канал роутера (обмеження одного радіомодуля ESP32). */
#define WIFI_MGR_AP_CHANNEL                   1
/* Максимальна кількість одночасно підключених телефонів/ноутбуків */
#define WIFI_MGR_AP_MAX_CLIENTS               4

/* ------------------------------------------------------------------------
 * Підключення до роутера при старті (є збережені дані)
 * ------------------------------------------------------------------------ */
/* Кількість спроб, після яких стартує Captive Portal */
#define WIFI_MGR_BOOT_CONNECT_ATTEMPTS        5
/* Пауза між спробами, мс */
#define WIFI_MGR_RETRY_DELAY_MS               1000
/* Максимальний час однієї спроби (асоціація + DHCP), мс */
#define WIFI_MGR_ATTEMPT_TIMEOUT_MS           15000

/* ------------------------------------------------------------------------
 * Перевірка даних, які користувач ввів на сторінці порталу
 * ------------------------------------------------------------------------ */
/* Кількість спроб підключення з новими даними до показу помилки */
#define WIFI_MGR_PORTAL_TEST_ATTEMPTS         2
/* Скільки портал ще живе після успіху, щоб сторінка встигла показати
 * результат користувачу, мс */
#define WIFI_MGR_PORTAL_SUCCESS_HOLD_MS       8000
/* Період фонових спроб підключитися до ЗБЕРЕЖЕНОЇ мережі, поки працює
 * портал (наприклад, роутер довго вмикався після збою живлення), мс.
 * Спроба відкладається, якщо до порталу хтось підключений. */
#define WIFI_MGR_PORTAL_SAVED_RETRY_MS        (5 * 60 * 1000)
/* Кількість спроб у межах однієї фонової перевірки */
#define WIFI_MGR_PORTAL_SAVED_RETRY_ATTEMPTS  3

/* ------------------------------------------------------------------------
 * Втрата з'єднання під час роботи: нескінченні повтори з експоненційною
 * паузою MIN, 2*MIN, 4*MIN ... MAX. Портал у цьому випадку НЕ вмикається.
 * ------------------------------------------------------------------------ */
#define WIFI_MGR_RECONNECT_BACKOFF_MIN_MS     1000
#define WIFI_MGR_RECONNECT_BACKOFF_MAX_MS     60000

/* ------------------------------------------------------------------------
 * Кнопка скидання налаштувань Wi-Fi
 * Утримання кнопки WIFI_MGR_RESET_HOLD_MS під час роботи -> дані Wi-Fi
 * стираються з NVS і запускається Captive Portal.
 * GPIO_NUM_NC вимикає функцію.
 * УВАГА: GPIO0 — strapping-пін. Якщо утримувати його під час подачі
 * живлення/RESET, чип увійде в режим прошивки. Тому кнопку натискають
 * ПІСЛЯ того, як пристрій запустився.
 * ------------------------------------------------------------------------ */
#define WIFI_MGR_RESET_GPIO                   GPIO_NUM_0
/* Рівень на піні при натиснутій кнопці (0 — кнопка замикає на GND) */
#define WIFI_MGR_RESET_ACTIVE_LEVEL           0
#define WIFI_MGR_RESET_HOLD_MS                3000
#define WIFI_MGR_RESET_DEBOUNCE_MS            50

/* ------------------------------------------------------------------------
 * Сканування мереж для списку на сторінці
 * ------------------------------------------------------------------------ */
#define WIFI_MGR_SCAN_MAX_APS                 20

/* ------------------------------------------------------------------------
 * Задача менеджера Wi-Fi
 * ------------------------------------------------------------------------ */
#define WIFI_MGR_TASK_STACK_SIZE              6144
#define WIFI_MGR_TASK_PRIORITY                5
#define WIFI_MGR_QUEUE_LENGTH                 12

#endif //MICROPLASTIC_APPWIFICONFIG_H
